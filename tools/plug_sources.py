#!/usr/bin/env python3
"""Generate lib/data/sources/user_source_config.dart from a local JSON file.

The script only plugs user-supplied URLs into already-compiled Dart adapters.
It does not download, discover, decompile, verify, or recommend source sites.

Usage:
  python3 tools/plug_sources.py tools/source-config.example.json --dry-run
  python3 tools/plug_sources.py my-sources.json
  python3 tools/plug_sources.py my-sources.json --defines
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "lib" / "data" / "sources" / "user_source_config.dart"

DART_TEMPLATE = '''// User-filled source configuration.
//
// Generated by tools/plug_sources.py from a local JSON config.
// Blank sources are skipped by lib/data/sources/user_configured_sources.dart.
// Do not commit private source URLs if your repository is public.

const userAnimeOnsenBaseUrl = String.fromEnvironment(
  'ANIKKU_ANIME_ONSEN_BASE_URL',
  defaultValue: {anime_onsen_base_url},
);
const userAnimeOnsenApiUrl = String.fromEnvironment(
  'ANIKKU_ANIME_ONSEN_API_URL',
  defaultValue: {anime_onsen_api_url},
);
const userAnimeOnsenSearchUrl = String.fromEnvironment(
  'ANIKKU_ANIME_ONSEN_SEARCH_URL',
  defaultValue: {anime_onsen_search_url},
);
const userAnimeOnsenName = String.fromEnvironment(
  'ANIKKU_ANIME_ONSEN_NAME',
  defaultValue: {anime_onsen_name},
);

const userAnikotoBaseUrl = String.fromEnvironment(
  'ANIKKU_ANIKOTO_BASE_URL',
  defaultValue: {anikoto_base_url},
);
const userAnikotoName = String.fromEnvironment(
  'ANIKKU_ANIKOTO_NAME',
  defaultValue: {anikoto_name},
);
const userAnikotoEpisodeListTemplate = String.fromEnvironment(
  'ANIKKU_ANIKOTO_EPISODE_LIST_TEMPLATE',
  defaultValue: {anikoto_episode_list_template},
);
const userAnikotoServerListTemplate = String.fromEnvironment(
  'ANIKKU_ANIKOTO_SERVER_LIST_TEMPLATE',
  defaultValue: {anikoto_server_list_template},
);
const userAnikotoStreamResolverTemplate = String.fromEnvironment(
  'ANIKKU_ANIKOTO_STREAM_RESOLVER_TEMPLATE',
  defaultValue: {anikoto_stream_resolver_template},
);
'''

URL_FIELDS = {
    ("animeOnsen", "baseUrl"),
    ("animeOnsen", "apiUrl"),
    ("animeOnsen", "searchUrl"),
    ("anikoto", "baseUrl"),
}

DEFAULTS = {
    "animeOnsen": {
        "name": "AnimeOnsen",
        "baseUrl": "",
        "apiUrl": "",
        "searchUrl": "",
    },
    "anikoto": {
        "name": "Anikoto",
        "baseUrl": "",
        "episodeListTemplate": "/ajax/episode/list/{id}",
        "serverListTemplate": "/ajax/server/list?servers={episode}",
        "streamResolverTemplate": "",
    },
}

DEFINE_KEYS = {
    ("animeOnsen", "name"): "ANIKKU_ANIME_ONSEN_NAME",
    ("animeOnsen", "baseUrl"): "ANIKKU_ANIME_ONSEN_BASE_URL",
    ("animeOnsen", "apiUrl"): "ANIKKU_ANIME_ONSEN_API_URL",
    ("animeOnsen", "searchUrl"): "ANIKKU_ANIME_ONSEN_SEARCH_URL",
    ("anikoto", "name"): "ANIKKU_ANIKOTO_NAME",
    ("anikoto", "baseUrl"): "ANIKKU_ANIKOTO_BASE_URL",
    ("anikoto", "episodeListTemplate"): "ANIKKU_ANIKOTO_EPISODE_LIST_TEMPLATE",
    ("anikoto", "serverListTemplate"): "ANIKKU_ANIKOTO_SERVER_LIST_TEMPLATE",
    ("anikoto", "streamResolverTemplate"): "ANIKKU_ANIKOTO_STREAM_RESOLVER_TEMPLATE",
}


def dart_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def validate_url(section: str, field: str, value: str) -> None:
    if not value:
        return
    parsed = urlparse(value)
    if parsed.scheme != "https" or not parsed.netloc:
        raise SystemExit(f"{section}.{field} must be an absolute https:// URL")


def validate_template(section: str, field: str, value: str) -> None:
    if not value:
        return
    if value.startswith("http://"):
        raise SystemExit(f"{section}.{field} must not use http://")
    if value.startswith("https://"):
        validate_url(section, field, value)
    elif not value.startswith("/"):
        raise SystemExit(f"{section}.{field} must be a /path template or https:// URL")
    for token in re.findall(r"\{([^}]+)\}", value):
        if token not in {"id", "episode", "epurl"}:
            raise SystemExit(f"{section}.{field} has unsupported placeholder {{{token}}}")


def merged_config(path: Path) -> dict[str, dict[str, str]]:
    raw = json.loads(path.read_text())
    if not isinstance(raw, dict):
        raise SystemExit("Config root must be a JSON object")
    config = {section: values.copy() for section, values in DEFAULTS.items()}
    for section in config:
        user = raw.get(section, {})
        if user is None:
            user = {}
        if not isinstance(user, dict):
            raise SystemExit(f"{section} must be a JSON object")
        for key in config[section]:
            if key in user:
                config[section][key] = str(user[key]).strip()
    for section, values in config.items():
        for field, value in values.items():
            if (section, field) in URL_FIELDS:
                validate_url(section, field, value)
            if field.endswith("Template"):
                validate_template(section, field, value)
    return config


def render_dart(config: dict[str, dict[str, str]]) -> str:
    return DART_TEMPLATE.format(
        anime_onsen_base_url=dart_string(config["animeOnsen"]["baseUrl"]),
        anime_onsen_api_url=dart_string(config["animeOnsen"]["apiUrl"]),
        anime_onsen_search_url=dart_string(config["animeOnsen"]["searchUrl"]),
        anime_onsen_name=dart_string(config["animeOnsen"]["name"]),
        anikoto_base_url=dart_string(config["anikoto"]["baseUrl"]),
        anikoto_name=dart_string(config["anikoto"]["name"]),
        anikoto_episode_list_template=dart_string(config["anikoto"]["episodeListTemplate"]),
        anikoto_server_list_template=dart_string(config["anikoto"]["serverListTemplate"]),
        anikoto_stream_resolver_template=dart_string(config["anikoto"]["streamResolverTemplate"]),
    )


def print_defines(config: dict[str, dict[str, str]]) -> None:
    parts: list[str] = []
    for section, values in config.items():
        for field, value in values.items():
            if value:
                parts.append(f"--dart-define={DEFINE_KEYS[(section, field)]}={value}")
    print(" ".join(parts))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path, help="Local JSON source config")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--dry-run", action="store_true", help="Print generated Dart instead of writing")
    parser.add_argument("--defines", action="store_true", help="Print equivalent flutter --dart-define flags")
    args = parser.parse_args()

    config = merged_config(args.config)
    if args.defines:
        print_defines(config)
        return
    dart = render_dart(config)
    if args.dry_run:
        print(dart)
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(dart)
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
